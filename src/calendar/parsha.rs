//! Weekly Torah readings and special Shabbat designations.
//!
//! [`Parsha`] covers the full annual cycle, combined readings used in common
//! years, and special Shabbatot (Shekalim, Zachor, and others). Look one up with
//! [`todays_parsha`](crate::calendar::HebrewHolidayCalendar::todays_parsha) and
//! [`special_parsha`](crate::calendar::HebrewHolidayCalendar::special_parsha).

